// 默认当前阶段（用于展示：基础/强化/冲刺），随日期自动定位
export function getPlan(key) {
  return STUDY_PLANS[key] || null
}

export function currentStageIndex(key) {
  // 按 EXAM_DATE 的日期自动算属于哪个阶段；也可以手改（未来版本支持手动切换）
  // 阶段时间线：
  //   阶段 0 基础：今天 → 2026-12-31
  //   阶段 1 强化：2027-01-01 → 2027-08-31
  //   阶段 2 冲刺：2027-09-01 → 2027-12-24
  const now = new Date().getTime()
  const toDate = (s) => new Date(s).getTime()
  const plan = STUDY_PLANS[key]
  if (!plan) return 0
  if (now >= toDate('2027-09-01')) return 2
  if (now >= toDate('2027-01-01')) return 1
  return 0
}

